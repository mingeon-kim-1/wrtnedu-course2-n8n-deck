def main() -> None:
    # Load titles for filename suffixes.
    titles: dict[str, str] = {}
    with open(JSONL, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            titles[row["slide_no"]] = row.get("title", "")

    written = 0
    for sn, body in NOTES.items():
        # Filename: <slide_no>_notes.md — render_index globs `<sn>_*.md`.
        fname = SCRIPT_DIR / f"{sn}_notes.md"
        title = titles.get(sn, "")
        content = f"# Slide {sn} — {title}\n\n*{body}*\n"
        fname.write_text(content, encoding="utf-8")
        written += 1
    print(f"Wrote {written} note files to {SCRIPT_DIR}")


if __name__ == "__main__":
    main()
